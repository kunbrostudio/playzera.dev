// 바구니에 담긴 풍선 줄의 치수 — 순수 함수. DOM을 모른다.
//
// ── 왜 계산이 필요한가 ★ ─────────────────────────────────────
//
// ken이 못박은 규칙 둘이 서로 잡아당긴다.
//   ① "위로 쌓이게 하지마" — 줄은 **한 줄**이다. 세로로 못 늘린다.
//   ② 바구니 안에 담긴 것처럼 보여야 한다 — 줄이 바구니 밖으로
//      삐져나오면 담긴 게 아니라 옆에 늘어놓은 게 된다.
//
// 한 줄인데 개수가 늘면 가로로 길어질 수밖에 없으니, 늘어나는 몫을
// **겹침으로 흡수**해야 한다. 4차 판은 겹침을 CSS에 -32%로 박아 뒀는데,
// 그러면 다섯 개만 담아도 바구니 폭을 넘는다. 개수를 보고 겹침을
// 정하면 몇 개가 담기든 줄 길이가 바구니 안에 머문다.
//
// ── 단위 주의 ★ ──────────────────────────────────────────────
//
// 여기서 내는 값은 **둘 다 줄 컨테이너 폭에 대한 %**다. CSS에서
// `margin-left`의 %는 자기 폭이 아니라 **부모(컨테이닝 블록)의 폭**을
// 기준으로 푼다 — 이걸 "풍선 폭의 몇 %"로 착각하고 쓰면 개수가 늘수록
// 어긋난다. 픽셀을 안 재므로 화면 크기·기기와 무관하고, DOM 없이
// 테스트할 수 있다.

/** 풍선 하나의 폭(줄 컨테이너 대비 %). 참고 그림처럼 큼직하게. */
export const ITEM_PCT = 34

// 겹침의 하한·상한 — 줄 컨테이너 폭 대비 %.
// 하한: 이보다 적게 겹치면 따로 떨어져 보여 "담긴" 느낌이 안 난다.
// 상한: 풍선 폭(34%)의 80%. 이보다 겹치면 뒤 풍선이 색 조각으로만 남는다.
const MIN_OVERLAP_PCT = ITEM_PCT * 0.12
const MAX_OVERLAP_PCT = ITEM_PCT * 0.80

/**
 * 풍선 n개를 한 줄에 앉히는 치수.
 *
 * 줄 전체 폭 = W + (n-1)·(W - M)  — W는 풍선 폭, M은 겹침(둘 다 컨테이너 %).
 * 이게 100%를 넘지 않으려면 M ≥ W - (100 - W)/(n-1)이다. 그 최소값을
 * 쓰되 위 두 문턱으로 자른다. 상한에 걸릴 만큼 많이 담았을 때는 줄이
 * 조금 넘치는데, 그때는 넘치게 두는 편이 낫다 — 더 겹치면 무엇이
 * 담겼는지 안 보인다.
 *
 * @param {number} count 담긴 풍선 개수
 * @returns {{ itemPct:number, overlapPct:number }} 둘 다 컨테이너 폭 대비 %
 */
export function pileMetrics(count) {
  const n = Math.max(0, Math.floor(count))
  if (n <= 1) return { itemPct: ITEM_PCT, overlapPct: MIN_OVERLAP_PCT }

  const need = ITEM_PCT - (100 - ITEM_PCT) / (n - 1)
  const m = Math.min(MAX_OVERLAP_PCT, Math.max(MIN_OVERLAP_PCT, need))
  return { itemPct: ITEM_PCT, overlapPct: m }
}
