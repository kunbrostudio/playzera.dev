// 이 판을 몇 칸으로 할 것인가 — **순수 함수 하나가 정본이다.**
//
// ── 왜 판 중간에 안 바꾸나 ★ ─────────────────────────────────
//
// "라운드가 오르면 5칸"이 처음 떠오르는 답인데 두 가지가 걸린다.
//
//   ① 아이가 혼란스럽다. 발밑 버튼이 셋이었다가 다섯이 되면 방금 배운 것이 어긋난다.
//   ② **기록이 섞인다.** `side_steps`는 칸을 옮긴 횟수라, 한 판 안에서 칸 수가
//      바뀌면 그 판의 숫자가 무엇을 뜻하는지 아무도 말할 수 없게 된다.
//
// 그래서 칸 수는 **판이 시작할 때 한 번** 정하고 끝까지 간다.
//
// ── 누가 고르나 ──────────────────────────────────────────────
//
// **카메라 준비 화면에서 아이가 고른다.** 레벨로 자동 전환하는 안도 있었는데,
// 그러면 어느 날 갑자기 판이 넓어지고 아이는 왜 그런지 모른다. 준비 화면에서는
// 누르는 즉시 미리보기의 점선이 바뀌어서 **내 방이 다섯으로 갈린 모습을 보고**
// 정할 수 있다 — 좁으면 거기서 바로 안다.
//
// 여기 남은 함수는 **처음 눌려 있을 값**을 정한다.
//
// ── 부모가 잠글 수 있어야 한다 ───────────────────────────────
//
// 5칸은 **집이 좁으면 물리적으로 안 된다.** 카메라에 2m가 담긴다면 한 칸이 40cm인데
// 아이 몸통이 30cm다. 칸 옮기기가 큰 동작이 아니라 발 옮기기가 되면 운동량은
// 오히려 줄어든다. 공간은 아이가 판단할 수 있는 것이 아니라 부모가 아는 것이다.

export const LANE_CHOICES = [3, 5]

/**
 * 준비 화면에서 **처음 눌려 있을** 칸 수.
 *
 * 기본은 3칸이다. 처음 켠 아이가 다섯 칸을 만나면 어디로 가야 할지 모른다 —
 * 넓히는 것은 해 보고 고르는 쪽이지 기본값이 아니다.
 *
 * @param {object} opts
 * @param {boolean} opts.lockNarrow 부모가 "좁은 공간"을 켰나
 * @returns {3|5}
 */
export function lanesFor({ lockNarrow = false } = {}) {
  return lockNarrow ? 3 : 3
}
