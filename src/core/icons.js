/** 면으로 칠하는 아이콘 — 선으로 그리면 존재감이 약하다. */
const FILLED = new Set(['play', 'pause', 'star', 'heart', 'sound', 'soundOff', 'flame', 'zap', 'egg'])

/**
 * 아이콘 SVG 한 조각.
 *
 * @param {keyof PATHS} name
 * @param {number} size  em 단위. 글자 크기를 따라가야 버튼 안에서 같이 커지고 작아진다.
 */
export function icon(name, size = 1.05) {
  const d = PATHS[name]
  // 조용히 빈 칸을 남기면 버튼에 글자만 남아 "왜 아이콘이 없지"를 화면에서 못 찾는다.
  if (!d) throw new Error(`[icons] '${name}'이 없다. src/core/icons.js에 추가해라.`)
  // 별·하트처럼 면으로 칠할 것은 목록(FILLED)이 안다. 부르는 쪽이 매번
  // "이건 채우기"를 기억해야 하면 같은 아이콘이 화면마다 다르게 보인다.
  const fill = FILLED.has(name) ? 'currentColor' : 'none'
  return `<svg class="pz-ico" viewBox="0 0 24 24" width="${size}em" height="${size}em"
    fill="${fill}" stroke="currentColor" stroke-width="2"
    stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${d}</svg>`
}

