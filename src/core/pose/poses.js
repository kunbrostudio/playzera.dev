// 요가 자세 사전 — **데이터다.** 자세를 늘릴 때 손대는 파일은 여기 하나다.
//
// ── 왜 요가인가 ──────────────────────────────────────────────
//
// `docs/07`의 3막 구성(준비 → 주 운동 → 정리)에서 **정리 막이 비어 있었다.**
// 불 끄기로 숨이 찬 뒤 숨을 고르는 자리, 그리고 유연·안정 축이 요가로 채워진다.
//
// ── 무엇을 넣고 무엇을 뺐나 ──────────────────────────────────
//
// **서서 하는 자세만 넣는다.** 정면 2D 웹캠의 한계는 요가에서도 그대로다.
//   다운독·고양이소·아기 자세  바닥에 손발을 짚거나 앉는다 → 프레임 밖이거나 서로 가린다
//   의자 자세·런지            앞뒤 깊이가 안 읽힌다 (런지는 이미 겪었다 — 점수 0.36)
//   비틀기류                  몸이 카메라를 등지면 좌우 랜드마크가 뒤집힌다
//
// ── 이름은 동물·사물로 ───────────────────────────────────────
//
// "브륵샤아사나"가 아니라 "나무". 4~8세는 이름으로 자세를 기억한다.
//
// ── 목표값 읽는 법 ───────────────────────────────────────────
//
//   [목표, 허용오차, 가중치, 판정방향]
//   'min'  목표 이상이면 만점 (더 폈다고 깎지 않는다)
//   'max'  목표 이하면 만점
//   없으면 양방향
//
// 각도는 도(°), 비율은 어깨너비 또는 키 기준이다(`poseMatch.js`의 `poseFeatures`).
// **허용오차는 넉넉하다.** 아이의 요가는 모양이 아니라 시도가 목적이다.

